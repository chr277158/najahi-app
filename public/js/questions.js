function getQuestionsBySubject(subjectId) {
    console.log('🔍 Looking for subject:', subjectId);
    
    // إذا كان المعرف يحتوي على _s2 أو _s4، نستخدمه مباشرة
    if (allQuestions[subjectId]) {
        const questions = allQuestions[subjectId];
        console.log(`✅ Found ${questions.length} questions for ${subjectId}`);
        return questions;
    }
    
    // إذا لم نجد، نبحث عن بديل مناسب
    console.warn(`⚠️ No exact match for ${subjectId}, trying fallback`);
    
    // fallbacks
    const fallbacks = {
        'calcul': 'calcul_s2',
        'maths': 'maths_s4',
        'eveil': 'eveil_s2',
        'civique': 'civique_s2'
    };
    
    if (fallbacks[subjectId] && allQuestions[fallbacks[subjectId]]) {
        return allQuestions[fallbacks[subjectId]];
    }
    
    return allQuestions['calcul'] || [];
}
